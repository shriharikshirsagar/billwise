"""ReportLab tax-invoice PDF built only from the stored invoice values."""
import os

from reportlab.lib import colors
from reportlab.lib.enums import TA_RIGHT
from reportlab.lib.pagesizes import A4
from reportlab.lib.styles import ParagraphStyle, getSampleStyleSheet
from reportlab.lib.units import mm
from reportlab.platypus import (KeepTogether, Paragraph, Preformatted, SimpleDocTemplate,
                                Spacer, Table, TableStyle)

import db
from billing import fmt
from theme import APP_NAME, COLORS, TAGLINE

NAVY = colors.HexColor(COLORS["navy"])
BLUE = colors.HexColor(COLORS["blue"])
ICE = colors.HexColor(COLORS["ice"])
GREEN = colors.HexColor(COLORS["green"])
TEXT = colors.HexColor(COLORS["text"])
MUTED = colors.HexColor(COLORS["muted"])
RED = colors.HexColor(COLORS["red"])


def invoice_dir():
    return db.app_path("Invoices")


def default_path(bill_no):
    safe = "".join(ch for ch in bill_no if ch.isalnum() or ch in "-_")
    return os.path.join(invoice_dir(), "%s.pdf" % safe)


def _styles():
    ss = getSampleStyleSheet()
    base = ParagraphStyle("b", parent=ss["Normal"], fontName="Helvetica", fontSize=9,
                          leading=12, textColor=TEXT)
    return {
        "base": base,
        "small": ParagraphStyle("s", parent=base, fontSize=8, leading=10, textColor=MUTED),
        "label": ParagraphStyle("l", parent=base, fontName="Helvetica-Bold"),
        "h": ParagraphStyle("h", parent=base, fontName="Helvetica-Bold", fontSize=11,
                            textColor=NAVY, leading=14),
        "right": ParagraphStyle("r", parent=base, alignment=TA_RIGHT),
    }


def _header(canvas, doc, inv):
    w, h = A4
    canvas.saveState()
    canvas.setFillColor(NAVY)
    canvas.rect(0, h - 28 * mm, w, 28 * mm, stroke=0, fill=1)
    canvas.setFillColor(GREEN)
    canvas.rect(0, h - 29.5 * mm, w, 1.5 * mm, stroke=0, fill=1)
    canvas.setFillColor(colors.white)
    canvas.setFont("Helvetica-Bold", 24)
    canvas.drawString(15 * mm, h - 15 * mm, APP_NAME)
    canvas.setFont("Helvetica", 9)
    canvas.drawString(15 * mm, h - 21 * mm, TAGLINE)
    canvas.setFont("Helvetica-Bold", 14)
    canvas.drawRightString(w - 15 * mm, h - 15 * mm, "TAX INVOICE")
    canvas.setFont("Helvetica", 9)
    canvas.drawRightString(w - 15 * mm, h - 21 * mm, "Invoice No: %s" % inv["bill_no"])
    if inv.get("status") == "CANCELLED":
        canvas.setFillColor(RED)
        canvas.setFont("Helvetica-Bold", 60)
        canvas.translate(w / 2, h / 2)
        canvas.rotate(35)
        canvas.setFillAlpha(0.18)
        canvas.drawCentredString(0, 0, "CANCELLED")
    canvas.restoreState()
    canvas.saveState()
    canvas.setFont("Helvetica", 8)
    canvas.setFillColor(MUTED)
    canvas.drawString(15 * mm, 10 * mm, "Generated by billwise - %s" % TAGLINE)
    canvas.drawRightString(w - 15 * mm, 10 * mm, "Page %d" % doc.page)
    canvas.restoreState()


def _kv_table(rows, st, col_widths):
    data = [[Paragraph(k, st["label"]), Paragraph(v or "-", st["base"])] for k, v in rows]
    t = Table(data, colWidths=col_widths)
    t.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"),
                           ("BOTTOMPADDING", (0, 0), (-1, -1), 1),
                           ("TOPPADDING", (0, 0), (-1, -1), 1)]))
    return t


def build_story(inv, store):
    st = _styles()
    story = []
    store_lines = [store.get("store_name") or ""]
    if store.get("store_address"):
        store_lines.append(store["store_address"])
    extra = []
    if store.get("store_phone"):
        extra.append("Phone: %s" % store["store_phone"])
    if store.get("store_gstin"):
        extra.append("GSTIN: %s" % store["store_gstin"])
    if store.get("store_state_label"):
        extra.append("State: %s" % store["store_state_label"])
    store_lines.append("  |  ".join(extra))
    seller = Paragraph("<br/>".join(x for x in store_lines if x) or "&nbsp;", st["base"])

    status = inv.get("status") or "ACTIVE"
    meta = [("Invoice No", inv["bill_no"]), ("Date", inv.get("date") or ""),
            ("Status", status)]
    if not inv["legacy"]:
        meta += [("Supply", "Intra-state (CGST + SGST)" if inv.get("supply_type") == "INTRA"
                  else "Inter-state (IGST)"),
                 ("Place of supply", inv.get("place_of_supply_label") or "-"),
                 ("Cashier", inv.get("created_by") or "-")]
    cust = [("Customer", inv.get("customer_name") or ""), ("Phone", inv.get("customer_no") or "")]
    if inv.get("customer_gstin"):
        cust.append(("GSTIN", inv["customer_gstin"]))

    top = Table([[seller, _kv_table(meta, st, [28 * mm, 52 * mm])],
                 [_kv_table(cust, st, [22 * mm, 68 * mm]), ""]],
                colWidths=[100 * mm, 80 * mm])
    top.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"),
                             ("LEFTPADDING", (0, 0), (-1, -1), 0),
                             ("BOTTOMPADDING", (0, 0), (-1, -1), 6)]))
    story += [Spacer(1, 4 * mm), top, Spacer(1, 3 * mm)]

    if inv["legacy"]:
        story.append(Paragraph("Bill details (recorded by the original application)", st["h"]))
        story.append(Spacer(1, 2 * mm))
        story.append(Preformatted((inv.get("bill_details") or "").expandtabs(8), st["base"]))
        return story

    intra = inv.get("supply_type") == "INTRA"
    head = ["#", "Item", "HSN", "Qty", "Rate (MRP)", "Disc.", "Taxable", "GST %"]
    head += ["CGST", "SGST"] if intra else ["IGST"]
    head += ["Amount"]
    data = [head]
    for it in inv["items"]:
        row = [str(it["line_no"]), Paragraph(it["product_name"], st["base"]), it.get("hsn_code") or "",
               str(it["qty"]), fmt(it["unit_price"]),
               fmt(it["discount_amount"]), fmt(it["taxable_amount"]),
               "%s%%" % it["gst_rate"]]
        row += [fmt(it["cgst_amount"]), fmt(it["sgst_amount"])] if intra else [fmt(it["igst_amount"])]
        row.append(fmt(it["line_total"]))
        data.append(row)
    if intra:
        widths = [7, 44, 14, 10, 18, 14, 18, 12, 15, 15, 21]
    else:
        widths = [7, 50, 15, 10, 19, 15, 20, 12, 17, 23]
    items = Table(data, colWidths=[w * mm for w in widths], repeatRows=1)
    items.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), NAVY), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"), ("FONTSIZE", (0, 0), (-1, -1), 8),
        ("ALIGN", (3, 0), (-1, -1), "RIGHT"), ("VALIGN", (0, 0), (-1, -1), "MIDDLE"),
        ("ROWBACKGROUNDS", (0, 1), (-1, -1), [colors.white, ICE]),
        ("LINEBELOW", (0, -1), (-1, -1), 0.8, BLUE),
    ]))
    story += [items, Spacer(1, 4 * mm)]

    totals = [("Subtotal (MRP)", fmt(inv["subtotal"])), ("Discount", "-" + fmt(inv["discount_total"])),
              ("Taxable amount", fmt(inv["taxable_total"]))]
    if intra:
        totals += [("CGST", fmt(inv["cgst_total"])), ("SGST", fmt(inv["sgst_total"]))]
    else:
        totals += [("IGST", fmt(inv["igst_total"]))]
    totals += [("Total GST", fmt(inv["tax_total"])), ("Round off", fmt(inv["round_off"])),
               ("TOTAL PAYABLE (Rs.)", fmt(inv["grand_total"]))]
    tot = Table([[k, v] for k, v in totals], colWidths=[45 * mm, 30 * mm], hAlign="RIGHT")
    tot.setStyle(TableStyle([
        ("ALIGN", (1, 0), (1, -1), "RIGHT"), ("FONTSIZE", (0, 0), (-1, -1), 9),
        ("TEXTCOLOR", (0, 0), (-1, -1), TEXT),
        ("BACKGROUND", (0, -1), (-1, -1), GREEN), ("TEXTCOLOR", (0, -1), (-1, -1), colors.white),
        ("FONTNAME", (0, -1), (-1, -1), "Helvetica-Bold"), ("FONTSIZE", (0, -1), (-1, -1), 11),
    ]))

    summary = [["GST %", "Taxable", "CGST", "SGST", "IGST"]]
    by_rate = {}
    for it in inv["items"]:
        r = by_rate.setdefault(it["gst_rate"], [0, 0, 0, 0])
        for i, f in enumerate(("taxable_amount", "cgst_amount", "sgst_amount", "igst_amount")):
            r[i] += it[f]
    for rate in sorted(by_rate):
        summary.append(["%s%%" % rate] + [fmt(v) for v in by_rate[rate]])
    gst = Table(summary, colWidths=[16 * mm, 22 * mm, 18 * mm, 18 * mm, 18 * mm])
    gst.setStyle(TableStyle([
        ("BACKGROUND", (0, 0), (-1, 0), BLUE), ("TEXTCOLOR", (0, 0), (-1, 0), colors.white),
        ("FONTNAME", (0, 0), (-1, 0), "Helvetica-Bold"), ("FONTSIZE", (0, 0), (-1, -1), 8),
        ("ALIGN", (1, 0), (-1, -1), "RIGHT"), ("GRID", (0, 0), (-1, -1), 0.3, MUTED),
    ]))
    pay = [("Payment mode", inv.get("payment_mode") or "-")]
    if inv.get("payment_ref"):
        pay.append(("Card (last 4)" if inv.get("payment_mode") == "Card" else "Reference",
                    inv["payment_ref"]))
    if inv.get("payment_mode") == "Cash":
        pay += [("Cash received", fmt(inv["amount_tendered"])), ("Change", fmt(inv["change_due"]))]
    left = [Paragraph("GST summary", st["h"]), Spacer(1, 1 * mm), gst, Spacer(1, 3 * mm),
            Paragraph("Payment", st["h"]), _kv_table(pay, st, [30 * mm, 60 * mm])]
    block = Table([[left, tot]], colWidths=[100 * mm, 80 * mm])
    block.setStyle(TableStyle([("VALIGN", (0, 0), (-1, -1), "TOP"),
                               ("LEFTPADDING", (0, 0), (-1, -1), 0)]))
    story.append(KeepTogether(block))
    story.append(Spacer(1, 5 * mm))
    note = "Prices are inclusive of GST. Thank you for shopping with us."
    if inv.get("status") == "CANCELLED":
        note = "This invoice was CANCELLED on %s. Reason: %s" % (
            inv.get("cancelled_at") or "", inv.get("cancel_reason") or "")
    story.append(Paragraph(note, st["small"]))
    return story


def store_details(conn):
    import gst_states
    s = {k: db.get_setting(conn, k) for k in
         ("store_name", "store_address", "store_phone", "store_gstin", "store_state_code")}
    s["store_state_label"] = gst_states.label(s["store_state_code"])
    return s


def generate_invoice_pdf(inv, store, path=None):
    path = path or default_path(inv["bill_no"])
    os.makedirs(os.path.dirname(path), exist_ok=True)
    tmp = path + ".tmp"
    doc = SimpleDocTemplate(tmp, pagesize=A4, leftMargin=15 * mm, rightMargin=15 * mm,
                            topMargin=34 * mm, bottomMargin=18 * mm,
                            title="Invoice %s" % inv["bill_no"], author=APP_NAME)
    page = lambda c, d: _header(c, d, inv)  # noqa: E731
    doc.build(build_story(inv, store), onFirstPage=page, onLaterPages=page)
    os.replace(tmp, path)  # never leave a half-written PDF under the real name
    return path
